-- ============================================================================
-- 10_schema.sql — Ward-Level Water Quality & Complaint Triage
-- ----------------------------------------------------------------------------
-- Target: Exasol Personal (local). Idempotent: safe to re-run at any time.
--
-- CONVENTIONS (each one exists because breaking it bites silently):
--   * Every identifier is UPPERCASE. Tables are pre-created before any CSV
--     load, because a file-loaded table keeps the CSV header case as a QUOTED
--     identifier and then `SELECT SUM(Visits)` fails with "object not found".
--   * No FOREIGN KEY / PRIMARY KEY enforcement is relied upon: Exasol records
--     declared PKs for documentation but does not enforce them. We declare PKs
--     because they are self-documenting and free.
--   * NO `DISTRIBUTED BY` / `PARTITION BY` clauses. They were in the original
--     design on the assumption that they are merely cosmetic on a single data
--     node. Measured against the live Personal build they are worse than
--     cosmetic: they do not parse. `CREATE TABLE X (A INT) DISTRIBUTED BY (A)`
--     fails with "syntax error, unexpected IDENTIFIER_PART_, expecting
--     END_OF_INPUT_ or ';'" — the distribution grammar is absent from this
--     edition. The clauses are therefore omitted, and nothing in this project
--     claims a distribution or partition-pruning speedup (see docs/decisions.md
--     ADR-004, which this note corrects).
--   * Paging uses `LIMIT n`. Exasol has no `FETCH FIRST` / `TOP`.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS WARDQ;

-- ---------------------------------------------------------------------------
-- WARD — one row per municipal ward (the geographic unit of the whole product)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TABLE WARDQ.WARD
(
    WARD_ID      DECIMAL(9,0)  NOT NULL,
    WARD_NAME    VARCHAR(120)  NOT NULL,
    CITY         VARCHAR(60)   NOT NULL,
    CITY_ZONE    VARCHAR(40)   NOT NULL,
    POPULATION   DECIMAL(12,0),
    CONNECTIONS  DECIMAL(12,0),          -- water connections served; denominator for complaint density
    DOWNSTREAM   BOOLEAN,                -- true if fed by the downstream treatment plant
    PRIMARY KEY (WARD_ID)
);
COMMENT ON TABLE  WARDQ.WARD IS 'Municipal wards monitored for water quality';
COMMENT ON COLUMN WARDQ.WARD.CONNECTIONS IS 'Number of water connections served, used as the complaint-density denominator';
COMMENT ON COLUMN WARDQ.WARD.DOWNSTREAM  IS 'True when the ward is fed by the downstream treatment plant (monsoon-sensitive)';

-- ---------------------------------------------------------------------------
-- PARAMETER_LIMITS — the measured quality parameters and their BIS 10500-aligned limits
-- This is a dimension table so thresholds are DATA, not code: a ward officer
-- can see exactly which limit was breached and change it without a redeploy.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TABLE WARDQ.PARAMETER_LIMITS
(
    PARAM_CODE   VARCHAR(12)  NOT NULL,
    PARAM_NAME   VARCHAR(60)  NOT NULL,
    UNIT         VARCHAR(20)  NOT NULL,
    THRESHOLD_LO DOUBLE,                 -- NULL = no lower limit
    THRESHOLD_HI DOUBLE,                 -- NULL = no upper limit
    PRIMARY KEY (PARAM_CODE)
);
COMMENT ON TABLE WARDQ.PARAMETER_LIMITS IS 'Measured water-quality parameters with acceptability limits (BIS 10500 aligned)';

-- ---------------------------------------------------------------------------
-- SAMPLE_LOG — the fact table. One row = one parameter reading at one ward on
-- one day at one sampling station. ~280k rows are generated by
-- 30_generate_readings.sql.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TABLE WARDQ.SAMPLE_LOG
(
    SAMPLE_ID      DECIMAL(18,0) NOT NULL,
    WARD_ID        DECIMAL(9,0)  NOT NULL,
    PARAM_CODE     VARCHAR(12)   NOT NULL,
    SAMPLE_DATE    DATE          NOT NULL,
    SAMPLE_TS      TIMESTAMP     NOT NULL,
    VALUE_DOUBLE   DOUBLE,               -- NULL = sample taken but result missing
    STATION_ID     DECIMAL(9,0)  NOT NULL,
    SOURCE_STATION VARCHAR(120),
    LAB_VERIFIED   BOOLEAN,              -- false = on-site sensor only
    PRIMARY KEY (SAMPLE_ID)
);
COMMENT ON TABLE  WARDQ.SAMPLE_LOG IS 'One row per ward x parameter x day x sampling station';
COMMENT ON COLUMN WARDQ.SAMPLE_LOG.VALUE_DOUBLE IS 'Measured value in PARAMETER_LIMITS.UNIT; NULL means the result was never recorded';
COMMENT ON COLUMN WARDQ.SAMPLE_LOG.LAB_VERIFIED IS 'TRUE = laboratory-confirmed; FALSE = on-site sensor reading only (can drift)';

-- ---------------------------------------------------------------------------
-- COMPLAINT — one row per citizen complaint message (parsed WhatsApp export or
-- register entry). CATEGORY/SEVERITY/CONFIDENCE/RULE_VERSION are written by the
-- explainable rule engine, so "why was this tagged contamination" is a query.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TABLE WARDQ.COMPLAINT
(
    COMPLAINT_ID  DECIMAL(18,0) NOT NULL,
    WARD_ID       DECIMAL(9,0),          -- NULL when the ward could not be inferred
    RECEIVED_TS   TIMESTAMP,
    SENDER_HANDLE VARCHAR(120),
    RAW_TEXT      VARCHAR(2000),
    CATEGORY      VARCHAR(20),           -- contamination | leakage | pressure | other
    SEVERITY      VARCHAR(10),           -- high | medium | low
    CONFIDENCE    DOUBLE,                -- 0..1, normalised matched rule weight
    RULE_VERSION  VARCHAR(20),
    RULE_EVIDENCE VARCHAR(400),          -- the phrase that fired, for the UI tooltip
    CHANNEL       VARCHAR(20),           -- whatsapp | register | call
    PRIMARY KEY (COMPLAINT_ID)
);
COMMENT ON TABLE  WARDQ.COMPLAINT IS 'Citizen complaint messages, categorised by the rule engine';
COMMENT ON COLUMN WARDQ.COMPLAINT.RULE_EVIDENCE IS 'The matched phrase that produced CATEGORY, so the tagging is explainable';

-- ---------------------------------------------------------------------------
-- Derived / materialised layer — THIS is what the API reads.
-- The dashboard never touches SAMPLE_LOG directly, which is what keeps it
-- sub-second on the 2 vCPU / 6 GB local VM.
-- ---------------------------------------------------------------------------

-- ward x parameter x day aggregate: the small table all windowing runs on
CREATE OR REPLACE TABLE WARDQ.WARD_DAILY
(
    SAMPLE_DATE  DATE         NOT NULL,
    WARD_ID      DECIMAL(9,0) NOT NULL,
    PARAM_CODE   VARCHAR(12)  NOT NULL,
    N_SAMPLES    DECIMAL(9,0),
    AVG_VALUE    DOUBLE,
    MIN_VALUE    DOUBLE,
    MAX_VALUE    DOUBLE,
    BREACH_FLAG  DECIMAL(9,0),          -- count of readings outside limits that day
    GENERATED_AT TIMESTAMP
);

-- ward x parameter x month: the anomaly story, one row per flagged combination
CREATE OR REPLACE TABLE WARDQ.ANOMALY_EVENT
(
    SAMPLE_MONTH     VARCHAR(7)   NOT NULL,   -- YYYY-MM
    WARD_ID          DECIMAL(9,0) NOT NULL,
    PARAM_CODE       VARCHAR(12)  NOT NULL,
    MOVING_AVG       DOUBLE,                  -- 30-day trailing mean, excluding today
    BASELINE_STDDEV  DOUBLE,
    Z_SCORE          DOUBLE,                  -- (month mean - trailing mean) / trailing stddev
    BREACH_DAYS      DECIMAL(9,0),
    CONSECUTIVE_RUN  DECIMAL(9,0),            -- longest run of consecutive breach days
    SLOPE_12M        DOUBLE,                  -- 12-month deterioration slope (units / day)
    SEVERITY         VARCHAR(10),
    GENERATED_AT     TIMESTAMP
);

-- ward x month composite risk: the single table behind the morning heatmap
CREATE OR REPLACE TABLE WARDQ.WARD_MONTH_RISK
(
    SAMPLE_MONTH      VARCHAR(7)   NOT NULL,
    WARD_ID           DECIMAL(9,0) NOT NULL,
    RISK_SCORE        DOUBLE,                 -- 0..100 from WARDQ.RISK_SCORE
    Z_COMPONENT       DOUBLE,
    BREACH_COMPONENT  DOUBLE,
    SLOPE_COMPONENT   DOUBLE,
    COMPLAINT_COMP    DOUBLE,
    COMPLAINT_DENSITY DOUBLE,                 -- complaints per 1000 connections
    WORST_PARAM       VARCHAR(12),
    RANK_IN_MONTH     DECIMAL(9,0),
    GENERATED_AT      TIMESTAMP
);

-- ward x category x month: the complaint side of the heatmap
CREATE OR REPLACE TABLE WARDQ.COMPLAINT_SUMMARY
(
    SAMPLE_MONTH  VARCHAR(7)   NOT NULL,
    WARD_ID       DECIMAL(9,0) NOT NULL,
    CATEGORY      VARCHAR(20)  NOT NULL,
    N_COMPLAINTS  DECIMAL(9,0),
    N_HIGH_SEV    DECIMAL(9,0),
    SAMPLE_TEXT   VARCHAR(400),               -- one representative quote for the UI
    GENERATED_AT  TIMESTAMP
);

-- Honest "data as of ..." footer + the load timings we quote in the PRD
CREATE OR REPLACE TABLE WARDQ.LOAD_RUN
(
    RUN_TS       TIMESTAMP,
    STEP         VARCHAR(60),
    ROWS_LOADED  DECIMAL(18,0),
    ELAPSED_MS   DECIMAL(18,0),
    LOAD_SOURCE       VARCHAR(200)
);

-- Measured performance, so every speed claim on screen comes from a real number
CREATE OR REPLACE TABLE WARDQ.BENCHMARK_RESULTS
(
    RUN_TS        TIMESTAMP,
    SCENARIO      VARCHAR(40),
    ENGINE        VARCHAR(20),                -- exasol | sqlite | python
    ROWS_TOUCHED  DECIMAL(18,0),
    ELAPSED_MS    DECIMAL(18,0),
    BYTES_SENT    DECIMAL(18,0),
    NOTE          VARCHAR(400)
);

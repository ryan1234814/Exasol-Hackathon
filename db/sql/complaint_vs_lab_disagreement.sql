SELECT
    lv.SAMPLE_MONTH,
    lv.WARD_ID,
    lv.WARD_NAME,
    lv.PARAM_CODE,
    lv.UNIT,
    lv.SENSOR_READINGS,
    lv.LAB_READINGS,
    lv.SENSOR_BREACHES,
    lv.LAB_BREACHES,
    COALESCE(csum.N_COMPLAINTS, 0) AS CITIZEN_COMPLAINTS_THAT_MONTH
FROM WARDQ.V_LAB_VS_SENSOR lv
LEFT JOIN (
    SELECT SAMPLE_MONTH, WARD_ID, SUM(N_COMPLAINTS) AS N_COMPLAINTS
    FROM WARDQ.COMPLAINT_SUMMARY
    WHERE CATEGORY = 'contamination'
    GROUP BY SAMPLE_MONTH, WARD_ID
) csum ON csum.SAMPLE_MONTH = lv.SAMPLE_MONTH AND csum.WARD_ID = lv.WARD_ID
WHERE lv.SENSOR_BREACHES > 0
  AND lv.LAB_BREACHES = 0
ORDER BY lv.SENSOR_BREACHES DESC, lv.SAMPLE_MONTH
LIMIT 25

SELECT
    r.RANK_IN_MONTH,
    r.WARD_ID,
    w.WARD_NAME,
    r.RISK_SCORE,
    r.WORST_PARAM,
    r.Z_COMPONENT,
    r.BREACH_COMPONENT,
    r.SLOPE_COMPONENT,
    r.COMPLAINT_COMP,
    COALESCE(s.N_COMPLAINTS, 0) AS N_COMPLAINTS,
    COALESCE(s.N_HIGH_SEV, 0)   AS N_HIGH_SEV
FROM WARDQ.WARD_MONTH_RISK r
JOIN WARDQ.WARD w ON w.WARD_ID = r.WARD_ID
LEFT JOIN (
    SELECT WARD_ID, SUM(N_COMPLAINTS) AS N_COMPLAINTS,
           SUM(N_HIGH_SEV) AS N_HIGH_SEV
    FROM WARDQ.COMPLAINT_SUMMARY
    WHERE SAMPLE_MONTH = (SELECT MAX(SAMPLE_MONTH) FROM WARDQ.WARD_MONTH_RISK)
    GROUP BY WARD_ID
) s ON s.WARD_ID = r.WARD_ID
WHERE r.SAMPLE_MONTH = (SELECT MAX(SAMPLE_MONTH) FROM WARDQ.WARD_MONTH_RISK)
ORDER BY r.RANK_IN_MONTH
LIMIT 10

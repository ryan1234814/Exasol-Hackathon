SELECT
    csum.SAMPLE_MONTH,
    csum.WARD_ID,
    w.WARD_NAME,
    csum.CATEGORY,
    csum.N_COMPLAINTS,
    csum.N_HIGH_SEV,
    ROUND(100.0 * csum.N_COMPLAINTS / NULLIF(SUM(csum.N_COMPLAINTS)
              OVER (PARTITION BY csum.WARD_ID, csum.SAMPLE_MONTH), 0), 1) AS PCT_OF_WARD_COMPLAINTS,
    csum.SAMPLE_TEXT AS REPRESENTATIVE_QUOTE
FROM WARDQ.COMPLAINT_SUMMARY csum
JOIN WARDQ.WARD w ON w.WARD_ID = csum.WARD_ID
WHERE csum.SAMPLE_MONTH = (SELECT MAX(SAMPLE_MONTH) FROM WARDQ.COMPLAINT_SUMMARY)
  AND csum.WARD_ID IN (
        SELECT WARD_ID FROM WARDQ.WARD_MONTH_RISK
        WHERE SAMPLE_MONTH = (SELECT MAX(SAMPLE_MONTH) FROM WARDQ.WARD_MONTH_RISK)
          AND RANK_IN_MONTH = 1
  )
ORDER BY csum.N_COMPLAINTS DESC
LIMIT 10

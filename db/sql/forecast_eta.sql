SELECT
    WARD_NAME,
    PARAM_CODE,
    UNIT,
    ROUND(RECENT_AVG, 3)  AS "CURRENT",
    ROUND(SLOPE_12M, 5)   AS SLOPE_PER_DAY,
    THRESHOLD_LO,
    THRESHOLD_HI,
    CASE WHEN SLOPE_12M IS NULL OR SLOPE_12M = 0 THEN NULL
         WHEN SLOPE_12M > 0 AND THRESHOLD_HI IS NOT NULL
              THEN ROUND((THRESHOLD_HI - RECENT_AVG) / SLOPE_12M, 1)
         WHEN SLOPE_12M < 0 AND THRESHOLD_LO IS NOT NULL
              THEN ROUND((RECENT_AVG - THRESHOLD_LO) / ABS(SLOPE_12M), 1)
         ELSE NULL END   AS DAYS_TO_BREACH,
    ROUND(RECENT_AVG + SLOPE_12M * 30, 3) AS PROJECTED_30D
FROM WARDQ.V_WARD_FORECAST
WHERE RECENT_AVG IS NOT NULL
ORDER BY DAYS_TO_BREACH
LIMIT 25

SELECT
    SUBSTR(CAST(d.SAMPLE_DATE AS VARCHAR(32)), 1, 7) AS SAMPLE_MONTH,
    CASE WHEN w.DOWNSTREAM THEN 'downstream' ELSE 'upstream' END AS FLOW_SIDE,
    COUNT(*)                                     AS WARD_DAYS,
    ROUND(AVG(d.AVG_VALUE), 2)                   AS AVG_TURBIDITY_NTU,
    SUM(d.BREACH_FLAG)                           AS BREACH_READINGS,
    ROUND(100.0 * SUM(CASE WHEN d.BREACH_FLAG > 0 THEN 1 ELSE 0 END) / COUNT(*), 1)
                                                 AS PCT_WARD_DAYS_IN_BREACH
FROM WARDQ.WARD_DAILY d
JOIN WARDQ.WARD w ON w.WARD_ID = d.WARD_ID
WHERE d.PARAM_CODE = 'TURBIDITY'
  AND SUBSTR(CAST(d.SAMPLE_DATE AS VARCHAR(32)), 6, 2) IN ('07', '08', '09')
GROUP BY SUBSTR(CAST(d.SAMPLE_DATE AS VARCHAR(32)), 1, 7),
         CASE WHEN w.DOWNSTREAM THEN 'downstream' ELSE 'upstream' END
ORDER BY SAMPLE_MONTH, AVG_TURBIDITY_NTU DESC
LIMIT 40

SELECT
    z.SAMPLE_DATE,
    z.WARD_ID,
    w.WARD_NAME,
    z.PARAM_CODE,
    ROUND(z.AVG_VALUE, 2)     AS DAY_AVG,
    ROUND(z.MOVING_AVG, 2)    AS TRAILING_30D_AVG,
    ROUND(z.BASELINE_STDDEV, 3) AS BASELINE_STDDEV,
    ROUND(z.Z_SCORE, 2)       AS Z_SCORE,
    z.BREACH_FLAG             AS READINGS_OUT_OF_LIMIT,
    z.BASELINE_N              AS DAYS_IN_BASELINE
FROM WARDQ.V_WARD_DAY_Z z
JOIN WARDQ.WARD w ON w.WARD_ID = z.WARD_ID
WHERE z.PARAM_CODE = 'COLIFORM'
  AND z.Z_SCORE >= 3
ORDER BY z.SAMPLE_DATE, z.Z_SCORE DESC
LIMIT 45

SELECT
    lv.SAMPLE_MONTH,
    lv.WARD_ID,
    lv.WARD_NAME,
    lv.PARAM_CODE,
    lv.LAB_READINGS,
    lv.SENSOR_READINGS,
    lv.LAB_BREACHES,
    lv.SENSOR_BREACHES,
    COALESCE(c.N_COMPLAINTS, 0) AS CONTAMINATION_COMPLAINTS,
    CASE WHEN lv.LAB_BREACHES > 0    THEN 'lab_confirmed'
         WHEN lv.SENSOR_BREACHES > 0 THEN 'instrument_suspect'
         ELSE 'consistent' END  AS VERDICT
FROM WARDQ.V_LAB_VS_SENSOR lv
LEFT JOIN (
    SELECT SAMPLE_MONTH, WARD_ID, SUM(N_COMPLAINTS) AS N_COMPLAINTS
    FROM WARDQ.COMPLAINT_SUMMARY
    WHERE CATEGORY = 'contamination'
    GROUP BY SAMPLE_MONTH, WARD_ID
) c ON c.SAMPLE_MONTH = lv.SAMPLE_MONTH AND c.WARD_ID = lv.WARD_ID
WHERE lv.SAMPLE_MONTH = (SELECT MAX(SAMPLE_MONTH) FROM WARDQ.WARD_MONTH_RISK)
ORDER BY lv.SENSOR_BREACHES DESC, lv.LAB_BREACHES
LIMIT 25

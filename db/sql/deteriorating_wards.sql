SELECT
    a.SAMPLE_MONTH,
    a.WARD_ID,
    w.WARD_NAME,
    w.CITY,
    a.PARAM_CODE,
    p.PARAM_NAME,
    p.UNIT,
    ROUND(a.SLOPE_12M, 5)      AS SLOPE_PER_DAY,
    ROUND(a.Z_SCORE, 2)        AS Z_SCORE,
    a.BREACH_DAYS,
    a.CONSECUTIVE_RUN,
    a.SEVERITY,
    ROUND(a.MOVING_AVG, 2)     AS TRAILING_AVG
FROM WARDQ.ANOMALY_EVENT a
JOIN WARDQ.WARD w      ON w.WARD_ID = a.WARD_ID
JOIN WARDQ.PARAMETER_LIMITS p ON p.PARAM_CODE = a.PARAM_CODE
WHERE a.SLOPE_12M IS NOT NULL
  AND a.SAMPLE_MONTH = (SELECT MAX(SAMPLE_MONTH) FROM WARDQ.ANOMALY_EVENT)
ORDER BY ABS(a.SLOPE_12M) DESC, a.Z_SCORE DESC
LIMIT 15

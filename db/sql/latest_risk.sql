SELECT
    r.SAMPLE_MONTH,
    r.RANK_IN_MONTH,
    r.WARD_ID,
    w.WARD_NAME,
    w.CITY,
    ROUND(r.RISK_SCORE, 2)        AS RISK_SCORE,
    r.WORST_PARAM,
    ROUND(r.Z_COMPONENT, 2)       AS Z_COMPONENT,
    ROUND(r.BREACH_COMPONENT, 2)  AS BREACH_COMPONENT,
    ROUND(r.SLOPE_COMPONENT, 2)   AS SLOPE_COMPONENT,
    ROUND(r.COMPLAINT_COMP, 2)    AS COMPLAINT_COMPONENT,
    ROUND(r.COMPLAINT_DENSITY, 2) AS COMPLAINTS_PER_1000_CONNECTIONS
FROM WARDQ.WARD_MONTH_RISK r
JOIN WARDQ.WARD w ON w.WARD_ID = r.WARD_ID
WHERE r.SAMPLE_MONTH = (SELECT MAX(SAMPLE_MONTH) FROM WARDQ.WARD_MONTH_RISK)
ORDER BY r.RANK_IN_MONTH
LIMIT 10
